#!/usr/bin/env python3
"""Validate a real matched TRAIN800 replay and fit fixed direct-loss units.

Input JSONL is one row per condition, generated by a SOURCE replay. Values must
be signed per-condition scores, not a minibatch mean. No model is run here.
"""
from __future__ import annotations
import argparse
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'src'), str(ROOT)]
from phycoflow_reconstruction.evaluation.adaptive_campaign import digest, immutable_json


def fit_units(panel, rows):
    ids = panel['sample_ids']
    if len(ids) != 800 or len(set(ids)) != 800:
        raise ValueError('the declared TRAIN800 panel must contain 800 unique IDs')
    if len(rows) != 800 or [row['sample_id'] for row in rows] != ids:
        raise ValueError('SOURCE replay must match every TRAIN800 ID in panel order')
    units = {}
    floors = {}
    for key in ('native', 'state', 'scale', 'shape'):
        vals = [float(row[key]) for row in rows]
        if not all(math.isfinite(x) for x in vals):
            raise ValueError(f'nonfinite {key} replay')
        if key == 'native' and any(x < 0 for x in vals):
            raise ValueError('native loss cannot be negative')
        mean = sum(x if key == 'native' else abs(x) for x in vals) / len(vals)
        floors[key] = mean <= 1e-8
        units[key] = max(mean, 1e-8)
    return units, floors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--panel', type=Path, required=True)
    parser.add_argument('--replay', type=Path, required=True)
    parser.add_argument('--receipt', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    panel = json.loads(args.panel.read_text())
    receipt = json.loads(args.receipt.read_text())
    if (receipt.get('status') != 'completed' or receipt.get('split') != 'train'
            or receipt.get('members') != 2 or receipt.get('panel_sha256') != digest(args.panel)
            or receipt.get('replay_sha256') != digest(args.replay)
            or receipt.get('weight_view') != 'ema_materialized'
            or receipt.get('query_law') != 'shared_source'):
        raise ValueError('completed SOURCE TRAIN800 J2 replay identity required')
    rows = [json.loads(line) for line in args.replay.read_text().splitlines() if line.strip()]
    units, floors = fit_units(panel, rows)
    if any(floors.values()):
        raise ValueError('unit floor active; inspect the observable before learning')
    immutable_json(args.output, {'schema': 'car_round5_source_units_v1',
        'units': units, 'floor_active': floors, 'sample_count': len(rows),
        'panel_sha256': digest(args.panel), 'replay_sha256': digest(args.replay),
        'receipt_sha256': digest(args.receipt), 'source_checkpoint_sha256': receipt['source_checkpoint_sha256'],
        'definition': 'mean native loss; mean absolute signed per-condition family score'})

if __name__ == '__main__':
    main()
